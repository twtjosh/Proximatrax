// Turns the raw results of a test run into the per-test report tables and the
// metrics, so every row traces to an execution. Run after the suites have
// written their results to testing-reports/test-evidence/.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const OUT = join(ROOT, "testing-reports");
const EV = join(OUT, "test-evidence");
const unescape = (s) => s.replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&#10;/g, " ").replace(/&amp;/g, "&");
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ").replace(/\u001b\[[0-9;]*m/g, "").slice(0, 300);

function junit(file) {
    const xml = readFileSync(join(EV, file), "utf8");
    const out = [];
    // Attribute values may hold an unescaped ">", so attributes are matched whole.
    for (const m of xml.matchAll(/<testcase((?:\s+[\w:-]+="[^"]*")*)\s*(\/>|>([\s\S]*?)<\/testcase>)/g)) {
        const name = unescape(/name="([^"]*)"/.exec(m[1])[1]);
        const body = m[3] ?? "";
        const skip = /<skipped[^>]*message="([^"]*)"/.exec(body);
        const fail = /<failure[^>]*message="([^"]*)"/.exec(body);
        out.push({ name, status: skip ? "BLOCKED" : fail || body.includes("<failure") ? "FAIL" : "PASS", note: skip ? unescape(skip[1]).replace(/^BLOCKED:\s*/, "") : fail ? unescape(fail[1]) : "" });
    }
    return out;
}

function playwright() {
    const r = JSON.parse(readFileSync(join(EV, "playwright/results.json"), "utf8"));
    const out = [];
    const walk = (s) => {
        for (const spec of s.specs ?? [])
            for (const t of spec.tests) {
                const last = t.results.at(-1);
                out.push({ name: spec.title, browser: t.projectName, status: last.status === "passed" ? "PASS" : "FAIL", note: (last.error?.message ?? "").split("\n").filter(Boolean).slice(0, 3).join(" ") });
            }
        (s.suites ?? []).forEach(walk);
    };
    r.suites.forEach(walk);
    return out;
}

const fields = (name) => name.split(" | ").map((s) => s.trim());
const actual = (t) => (t.status === "PASS" ? "As expected" : t.note || (t.status === "BLOCKED" ? "Not executed" : "Assertion failed"));
const tally = (list) => {
    const passed = list.filter((t) => t.status === "PASS").length, failed = list.filter((t) => t.status === "FAIL").length, blocked = list.filter((t) => t.status === "BLOCKED").length;
    return { planned: list.length, executed: passed + failed, passed, failed, blocked, notRun: 0, passRate: passed + failed ? Number(((passed / (passed + failed)) * 100).toFixed(1)) : null };
};
const areas = (list) => {
    const by = new Map();
    for (const t of list) {
        const a = t.name.slice(0, 5);
        by.set(a, [...(by.get(a) ?? []), t]);
    }
    return [...by].sort(([a], [b]) => a.localeCompare(b));
};
const summary = (list) => ["| Area | Planned | Passed | Failed | Blocked |", "|---|---|---|---|---|", ...areas(list).map(([a, ts]) => {
    const c = tally(ts);
    return `| ${a} | ${c.planned} | ${c.passed} | ${c.failed} | ${c.blocked} |`;
})].join("\n");

const unitAll = junit("final/unit.junit.xml");
const unit = unitAll.filter((t) => /^UT-\d/.test(t.name));
const existing = unitAll.filter((t) => !/^UT-\d/.test(t.name));
const integration = junit("final/integration.junit.xml");
const sysRun = playwright();
const sysBlocked = junit("final/system-blocked.junit.xml");

const header = (title, intro) => `# ${title}\n\nGenerated by \`npm run test:report\` from the raw results in \`test-evidence/final/\` and \`test-evidence/playwright/results.json\`. Do not edit by hand: each row exists because that test ran.\n\n${intro}\n`;

writeFileSync(join(OUT, "unit-testing-report.md"), `${header("Unit Testing Report", `The pure logic, services, route handlers and UI store, run by the Node.js test runner with Supabase replaced by a recording stand-in. Input and expected values are in each row. Evidence: \`test-evidence/final/unit.log\`, coverage in \`test-evidence/final/unit-coverage.log\`.\n\nThe repository's ${existing.length} earlier unit tests ran in the same execution (${tally(existing).passed} passed, ${tally(existing).failed} failed). They are counted in the totals below and listed by name in the evidence log.`)}\n## Summary\n\n${summary(unit)}\n| Earlier suite | ${existing.length} | ${tally(existing).passed} | ${tally(existing).failed} | 0 |\n\n## Results\n\n| Test ID | Function/module | Test objective | Input | Expected result | Actual result | Status | Evidence |\n|---|---|---|---|---|---|---|---|\n${unit.map((t) => {
    const [id, fn, purpose, input, expected] = fields(t.name);
    return `| ${id} | ${cell(fn)} | ${cell(purpose)} | ${cell(input)} | ${cell(expected)} | ${cell(actual(t))} | ${t.status} | unit.log |`;
}).join("\n")}\n`);

writeFileSync(join(OUT, "integration-testing-report.md"), `${header("Integration Testing Report", `Run on PGlite (PostgreSQL 18 in-process) after applying the repository's migrations 0001 to 0030 to a new database. Each statement runs as an individual user under the \`authenticated\` or \`anon\` role with row-level security active, the same way PostgREST runs it. Persisted state is read back separately. Evidence: \`test-evidence/final/integration.log\`, and \`test-evidence/final/integration-before-fix.log\` for the same suite on migrations 0001 to 0029.\n\n**Limit of this evidence:** it proves the migration files, not the live database. Policies added by hand in the Supabase dashboard are invisible here. PostgREST, Auth, Realtime delivery and the Storage API are not present, and the rows that need them are BLOCKED.`)}\n## Summary\n\n${summary(integration)}\n\n## Results\n\n| Test ID | Connected modules | Test scenario | Input | Expected integration behavior | Actual integration behavior | Database verification | Status |\n|---|---|---|---|---|---|---|---|\n${integration.map((t) => {
    const [id, fn, purpose, input, expected] = fields(t.name);
    return `| ${id} | ${cell(fn)} | ${cell(purpose)} | ${cell(input)} | ${cell(expected)} | ${cell(actual(t))} | ${t.status === "BLOCKED" ? "None" : "Read back by the test"} | ${t.status} |`;
}).join("\n")}\n`);

const browserName = { "local-chromium": "Chromium (Edge), local build", "local-firefox": "Firefox, local build", "local-webkit": "WebKit, local build", "prod-readonly": "Chromium (Edge), production, read-only" };
const sysAll = [...sysRun, ...sysBlocked];
const sysRows = [...sysRun.map((t) => {
    const [id, role, workflow, expected] = fields(t.name);
    return `| ${id} | ${cell(role)} | ${browserName[t.browser]} | ${cell(workflow)} | ${cell(expected)} | ${cell(actual(t))} | ${t.status === "PASS" ? "results.json" : "results.json, screenshot in artifacts/"} | ${t.status} |`;
}), ...sysBlocked.map((t) => {
    const [id, , purpose] = fields(t.name);
    return `| ${id} | Signed-in user | None | ${cell(purpose)} | n/a | ${cell(t.note)} | None | BLOCKED |`;
})].sort();
writeFileSync(join(OUT, "system-testing-report.md"), `${header("System Testing Report", `Playwright against a local production build wired to an unreachable Supabase URL, in three browser engines, plus read-only checks of the public pages on https://proximatrax.vercel.app (every non-GET request aborted). A test run in three browsers counts as three executions. Chromium ran through installed Microsoft Edge. Evidence: \`test-evidence/playwright/html/index.html\`, \`results.json\`, \`performance-production.json\`.\n\nEverything that requires signing in is BLOCKED: no staging deployment or Supabase test project exists, and production must not be changed.`)}\n## Summary\n\n${summary(sysAll)}\n\n## Results\n\n| Test ID | User role | Browser/device | Workflow | Expected result | Actual result | Evidence | Status |\n|---|---|---|---|---|---|---|---|\n${sysRows.join("\n")}\n`);

const metrics = { generated: new Date().toISOString(), unit: tally([...unit, ...existing]), unitNew: tally(unit), unitExisting: tally(existing), integration: tally(integration), system: tally(sysAll), failures: { integration: integration.filter((t) => t.status === "FAIL").map((t) => t.name.split(" | ")[0]), system: sysRun.filter((t) => t.status === "FAIL").map((t) => `${t.name.split(" | ")[0]} [${t.browser}]`), unit: [...unit, ...existing].filter((t) => t.status === "FAIL").map((t) => t.name.split(" | ")[0]) } };
writeFileSync(join(EV, "final/metrics.json"), JSON.stringify(metrics, null, 2));
console.log(JSON.stringify(metrics, null, 2));
if (existsSync(join(EV, "final/integration-before-fix.junit.xml"))) {
    const before = junit("final/integration-before-fix.junit.xml");
    console.log("before fix:", JSON.stringify(tally(before)));
    writeFileSync(join(EV, "final/regression-comparison.json"), JSON.stringify({ before: tally(before), after: tally(integration), fixed: before.filter((t) => t.status === "FAIL" && integration.find((x) => x.name === t.name)?.status === "PASS").map((t) => t.name), stillFailing: integration.filter((t) => t.status === "FAIL").map((t) => t.name) }, null, 2));
}
